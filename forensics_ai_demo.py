"""EP02 示範：模擬「相機照片」vs 模擬「AI 上採樣圖」
EP02 demo: simulated camera-like photo vs simulated AI-like upsampled image.
所有圖片皆由本程式生成（無真實照片），這是模擬。
All images are generated by this script (no real photos). This is a SIMULATION."""
import numpy as np, cv2, os, json
from PIL import Image
rng = np.random.default_rng(42); N = 512; OUT = "out"; os.makedirs(OUT, exist_ok=True)  # 輸出資料夾 output folder

def scene(n):
    y, x = np.mgrid[0:n, 0:n] / n
    img = np.zeros((n, n, 3), np.float32)
    img[..., 0] = 0.5 + 0.4*y; img[..., 1] = 0.6 - 0.2*y; img[..., 2] = 0.9 - 0.5*y  # BGR sky
    g = y > 0.65; img[g] = [0.2, 0.55, 0.25]
    cv2.circle(img, (int(n*.75), int(n*.25)), n//10, (0.3, 0.85, 1.0), -1)
    cv2.rectangle(img, (int(n*.2), int(n*.45)), (int(n*.4), int(n*.7)), (0.3, 0.3, 0.7), -1)
    return cv2.GaussianBlur(img, (0, 0), n/256)

# 模擬相機：全解析度場景 + 散粒雜訊 + 固定感光元件圖樣（類 PRNU）
# Camera-like: full-res scene + shot noise + fixed sensor pattern (PRNU-like)
real = scene(N); prnu = 1 + 0.03*rng.standard_normal((N, N, 1))
real = real*prnu + rng.normal(0, 0.02, real.shape) * np.sqrt(real + .05)
# 模擬 AI：低解析度 -> 兩次 2 倍最近鄰放大 + 棋盤格（類轉置卷積）-> 輕微模糊
# AI-like: low-res -> 2x nearest twice + checkerboard (transposed-conv-like) -> slight blur
low = scene(N//4) + rng.normal(0, 0.01, (N//4, N//4, 3))
ai = cv2.resize(cv2.resize(low, (N//2, N//2), interpolation=cv2.INTER_NEAREST), (N, N), interpolation=cv2.INTER_NEAREST)
ai += 0.02*np.tile(np.array([[1, -1], [-1, 1]], np.float32)[..., None], (N//2, N//2, 3))  # 棋盤格痕跡 checkerboard artifact
ai = cv2.GaussianBlur(ai, (3, 3), 0.6)
to8 = lambda a: np.clip(a*255, 0, 255).astype(np.uint8)
real8, ai8 = to8(real), to8(ai)
cv2.imwrite(f"{OUT}/00_real_like.png", real8); cv2.imwrite(f"{OUT}/00_ai_like.png", ai8)
cv2.imwrite(f"{OUT}/00_compare.png", np.hstack([real8, np.full((N, 8, 3), 255, np.uint8), ai8]))

def spectrum(g):
    g = g.astype(np.float32) - cv2.GaussianBlur(g.astype(np.float32), (0, 0), 2)  # 高通殘差 high-pass residual
    F = np.fft.fftshift(np.abs(np.fft.fft2(g * np.outer(np.hanning(N), np.hanning(N)))))
    return np.log1p(F)
def peak_score(S):
    # 週期 2／4 頻率位置的能量 ÷ 中位數  energy at period-2/4 frequencies vs median
    c = N//2; pts = [(c, 0), (0, c), (0, 0), (c, c//2), (c//2, c), (c, c+c//2), (c+c//2, c)]
    return float(np.mean([S[p] for p in pts]) / np.median(S))
res = {}
for name, im in [("real", real8), ("ai", ai8)]:
    g = cv2.cvtColor(im, cv2.COLOR_BGR2GRAY); S = spectrum(g)
    cv2.imwrite(f"{OUT}/01_fft_{name}.png", to8(S / S.max()))
    r = g.astype(np.float32) - cv2.medianBlur(g, 3).astype(np.float32)
    blocks = r.reshape(N//32, 32, N//32, 32).std(axis=(1, 3))
    hm = cv2.applyColorMap(to8(cv2.resize(blocks/6, (N, N), interpolation=cv2.INTER_NEAREST)), cv2.COLORMAP_JET)
    cv2.imwrite(f"{OUT}/02_noise_{name}.png", hm)
    # 相鄰像素完全相同的比例（放大過的圖較高）  fraction of identical neighbour pixels (higher if upscaled)
    dup = float(np.mean(im[:, 0::2] == im[:, 1::2]))
    res[name] = dict(fft_peak_ratio=round(peak_score(S), 2), noise_mean=round(float(blocks.mean()), 2),
                     noise_cv=round(float(blocks.std()/blocks.mean()), 2), equal_neighbour_frac=round(dup, 3))
sR = cv2.imread(f"{OUT}/01_fft_real.png"); sA = cv2.imread(f"{OUT}/01_fft_ai.png")
cv2.imwrite(f"{OUT}/01_fft_compare.png", np.hstack([sR, np.full((N, 8, 3), 255, np.uint8), sA]))
# Metadata／C2PA 簡易檢查（僅搜尋位元組，正式驗證請用 c2patool）
# Metadata / C2PA quick check (byte search only; use c2patool for real verification)
def meta(p):
    b = open(p, "rb").read(); ex = Image.open(p).getexif()
    return dict(exif_tags=len(ex), c2pa=(b"c2pa" in b or b"jumb" in b))
res["meta_ai"] = meta(f"{OUT}/00_ai_like.png")
json.dump(res, open(f"{OUT}/results.json", "w"), indent=1); print(json.dumps(res, indent=1))
print(f"結果已存到 {OUT}/ ｜ Results saved to {OUT}/")
print("提醒：這是模擬，沒有單一方法能證明 AI 生成 ｜ Note: simulation only; no single method proves AI generation")
